"""
Facial Blendshapes Generation via Deformation Transfer (ARKit 52 Blendshapes)

Transfers 52 standard Apple ARKit facial blendshapes from template meshes onto arbitrary
target 3D character/head meshes generated by TRELLIS.2, Hunyuan3D, or uploaded by user.
Produces glTF 2.0 morph targets compatible with Three.js, Unreal Engine, Unity, Blender,
and Apple ARKit / FaceID tracking.

A shape is transferred by fitting the template onto the target head and then reading the
template's displacement field at each target vertex through that fit. The fit runs in the
two stages `flame-fitting/fit_lmk3d.py` uses -- rigid first, then non-rigid under a
regulariser -- driven by dense landmarks embedded barycentrically on the template. See
`pipeline/template_fit.py`.

Reference:
- vasiliskatr/deformation_transfer_ARkit_blendshapes (MIT License)
- Amberg et al.: Optimal Step Nonrigid ICP Algorithms for Surface Registration (CVPR 2007)
- Rubikplayer/flame-fitting, yfeng95/DECA -- for the fitting structure and the barycentric
  landmark embedding. Method only: both carry a non-commercial MPG licence, so no code
  from either is used here.

Not Sumner & Popović (SIGGRAPH 2004), which this file used to cite: that method solves a
least-squares system for the target's vertex positions from per-triangle deformation
gradients. It earns its cost on shapes with large rotation -- jawOpen, mouthSmile -- and
those are not in this file's scope, which is the 19 eye and brow shapes.
"""

